#!/usr/bin/env python3
"""Inspect PNG alpha bounds using stdlib; --write refreshes Dart metadata."""
import argparse, struct, zlib
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]

def inspect(path):
    raw = path.read_bytes(); pos = 8; compressed = bytearray(); transparency = b''
    while pos < len(raw):
        n = struct.unpack('>I', raw[pos:pos+4])[0]; tag = raw[pos+4:pos+8]; data = raw[pos+8:pos+8+n]; pos += n+12
        if tag == b'IHDR': w,h,depth,kind,_,_,interlace = struct.unpack('>IIBBBBB',data)
        if tag == b'IDAT': compressed.extend(data)
        if tag == b'tRNS': transparency = data
    if depth != 8 or interlace: raise ValueError(f'Unsupported PNG: {path}')
    channels = {6:4,2:3,3:1,0:1,4:2}[kind]; stride=w*channels
    pixels = zlib.decompress(compressed); prev=bytearray(stride); cursor=0
    left,top,right,bottom=w,h,0,0
    for y in range(h):
        filt=pixels[cursor]; row=bytearray(pixels[cursor+1:cursor+1+stride]);cursor+=stride+1
        for x in range(stride):
            a=row[x-channels] if x>=channels else 0;b=prev[x];c=prev[x-channels] if x>=channels else 0
            if filt==1: row[x]=(row[x]+a)&255
            elif filt==2: row[x]=(row[x]+b)&255
            elif filt==3: row[x]=(row[x]+((a+b)//2))&255
            elif filt==4:
                p=a+b-c; ds=[abs(p-a),abs(p-b),abs(p-c)]
                row[x]=(row[x]+[a,b,c][ds.index(min(ds))])&255
            elif filt!=0: raise ValueError(filt)
        for x in range(w):
            alpha=row[x*channels+channels-1] if kind in (4,6) else (transparency[row[x]] if kind==3 and row[x]<len(transparency) else 255)
            if alpha>8:left=min(left,x);top=min(top,y);right=max(right,x+1);bottom=max(bottom,y+1)
        prev=row
    if right<=left: raise ValueError(f'Empty image: {path}')
    return w,h,left,top,right-left,bottom-top

def generate():
    entries=[]
    for species in ['sunflower','hydrocotyle','cyperus','lavender','rose']:
        for stage in range(6):
            key=f'{species}_{stage}';v=inspect(ROOT/f'app/assets/game/plant_iso_{species}_stage{stage}.png')
            entries.append(f"  '{key}': GardenSpriteMetadata(Size({v[0]}, {v[1]}), Rect.fromLTWH({v[2]}, {v[3]}, {v[4]}, {v[5]})),")
    return "// Generated by tools/garden_asset_inventory.py; alpha > 8 visible bounds.\npart of 'garden_asset_catalog.dart';\n\nconst gardenSpriteMetadata = <String, GardenSpriteMetadata>{\n"+'\n'.join(entries)+'\n};\n'

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--write',action='store_true');args=parser.parse_args()
    target=ROOT/'feature_game/lib/src/garden/garden_asset_metadata.dart';content=generate()
    if args.write:target.write_text(content)
    else:
        # Dart format may change whitespace without changing the inventory.
        import re
        normalize = lambda value: re.sub(r',(?=[)}])', '', re.sub(r'\s', '', value))
        if not target.exists() or normalize(target.read_text()) != normalize(content):raise SystemExit('Asset metadata drift; inspect assets and run --write')
    print('PASS: 30 plant PNG dimensions and alpha bounds')
